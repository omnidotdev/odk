//! TypeScript model generation.
//!
//! Emits a `models.ts` of plain interfaces, one `export interface` per model
//! and one `export type` string-literal union per string union.
//!
//! # Why interfaces rather than classes
//!
//! Generated code inherits its shape onto every consumer. A schema describing
//! a file format (the motivating case is a DAW project document) wants to
//! describe the JSON it reads without pulling a runtime in first. Interfaces
//! are erased at compile time, so the output is pure type information with no
//! runtime cost and no dependency.
//!
//! The cost is that this validates nothing beyond shape: an out-of-range value
//! that the JSON Schema would reject still type-checks. Constraints in the IR
//! are emitted as comments so they are visible, not enforced.

use std::collections::BTreeMap;

use odk_schema::{CompiledField, CompiledSchema, CompiledType, LiteralValue, ScalarType};

/// Generate TypeScript models for a schema.
pub fn generate(schema: &CompiledSchema) -> BTreeMap<String, String> {
    let mut output = BTreeMap::new();

    if schema.models.is_empty() && schema.unions.is_empty() {
        return output;
    }

    output.insert("models.ts".to_string(), generate_models(schema));
    output
}

fn generate_models(schema: &CompiledSchema) -> String {
    let mut out = String::new();

    out.push_str(&format!(
        "// {} models.\n//\n// Generated by ODK. Do not edit by hand.\n\n",
        schema.name
    ));

    for union in &schema.unions {
        if let Some(desc) = &union.description {
            out.push_str(&format!("// {}\n", one_line(desc)));
        }

        // a discriminator tag marks a data-carrying union, emitted as a
        // discriminated union; otherwise it is a plain string-literal union
        if let Some(tag) = &union.tag {
            out.push_str(&discriminated_union(union, tag));
        } else {
            let variants: Vec<String> = union
                .variants
                .iter()
                .map(|v| format!("\"{}\"", escape(&v.name)))
                .collect();
            out.push_str(&format!(
                "export type {} = {};\n\n",
                union.name,
                variants.join(" | ")
            ));
        }
    }

    for model in &schema.models {
        out.push_str(&interface(model));
        out.push('\n');
    }

    out
}

/// Render a data-carrying union as a TypeScript discriminated union: one object
/// type per variant, each carrying the discriminator property plus the
/// variant's payload. Recursion needs no indirection in TypeScript.
fn discriminated_union(union: &odk_schema::CompiledUnion, tag: &str) -> String {
    let mut parts: Vec<String> = Vec::new();
    for v in &union.variants {
        let mut props = vec![format!("{tag}: \"{}\"", escape(&v.name))];
        match &v.variant_type {
            Some(CompiledType::Object { fields }) => {
                for f in fields {
                    let key = property_name(&f.name);
                    let marker = if f.optional == Some(true) { "?" } else { "" };
                    props.push(format!("{key}{marker}: {}", type_to_ts(&f.field_type)));
                }
                parts.push(format!("{{ {} }}", props.join("; ")));
            }
            Some(CompiledType::Ref { name }) => {
                // a referenced payload is intersected with the tag object
                parts.push(format!("({{ {} }} & {name})", props.join("; ")));
            }
            Some(other) => {
                props.push(format!("value: {}", type_to_ts(other)));
                parts.push(format!("{{ {} }}", props.join("; ")));
            }
            None => parts.push(format!("{{ {} }}", props.join("; "))),
        }
    }
    format!(
        "export type {} =\n  | {};\n\n",
        union.name,
        parts.join("\n  | ")
    )
}

fn interface(model: &odk_schema::CompiledModel) -> String {
    let mut out = String::new();

    if let Some(desc) = &model.description {
        out.push_str(&format!("// {}\n", one_line(desc)));
    }

    if model.fields.is_empty() {
        out.push_str(&format!("export interface {} {{}}\n", model.name));
        return out;
    }

    out.push_str(&format!("export interface {} {{\n", model.name));

    for f in &model.fields {
        if let Some(desc) = &f.description {
            out.push_str(&format!("  // {}\n", one_line(desc)));
        }
        if let Some(note) = constraint_note(f) {
            out.push_str(&format!("  // {note}\n"));
        }

        let key = property_name(&f.name);
        let marker = if f.optional == Some(true) { "?" } else { "" };
        out.push_str(&format!(
            "  {key}{marker}: {};\n",
            type_to_ts(&f.field_type)
        ));
    }

    out.push_str("}\n");
    out
}

/// Map an IR type onto a TypeScript type.
fn type_to_ts(t: &CompiledType) -> String {
    match t {
        CompiledType::Scalar { name } => scalar_to_ts(name).to_string(),
        // a fixed length becomes a TypeScript tuple, holding the size invariant
        CompiledType::Array {
            items,
            length: Some(n),
        } => {
            let inner = type_to_ts(items);
            format!("[{}]", vec![inner; *n as usize].join(", "))
        }
        CompiledType::Array {
            items,
            length: None,
        } => {
            let inner = type_to_ts(items);
            // a bare union or literal-union as an element binds looser than the
            // array suffix, so it has to be parenthesized to stay an array of
            // that whole type
            if needs_parens_as_array_element(items) {
                format!("({inner})[]")
            } else {
                format!("{inner}[]")
            }
        }
        CompiledType::Ref { name } => name.clone(),
        CompiledType::Literal { value } => match value {
            LiteralValue::String(s) => format!("\"{}\"", escape(s)),
            LiteralValue::Number(n) => format!("{n}"),
            LiteralValue::Bool(b) => format!("{b}"),
        },
        CompiledType::Union { variants } => {
            let parts: Vec<String> = variants.iter().map(type_to_ts).collect();
            parts.join(" | ")
        }
        // an inline object has no name to reference, so it stays an index signature
        CompiledType::Object { .. } => "Record<string, unknown>".to_string(),
    }
}

/// Whether a type rendered as an array element needs wrapping in parentheses.
fn needs_parens_as_array_element(t: &CompiledType) -> bool {
    matches!(t, CompiledType::Union { variants } if variants.len() > 1)
}

fn scalar_to_ts(s: &ScalarType) -> &'static str {
    match s {
        ScalarType::String
        | ScalarType::Date
        | ScalarType::Datetime
        | ScalarType::UtcDateTime
        | ScalarType::OffsetDateTime
        | ScalarType::PlainDate
        | ScalarType::PlainTime
        | ScalarType::Duration
        | ScalarType::Bytes
        | ScalarType::Url => "string",
        ScalarType::Int32 | ScalarType::Int64 | ScalarType::Float32 | ScalarType::Float64 => {
            "number"
        }
        ScalarType::Boolean => "boolean",
        ScalarType::Unknown => "unknown",
    }
}

/// Render a field's constraints as a human-readable note.
fn constraint_note(f: &CompiledField) -> Option<String> {
    let c = f.constraints.as_ref()?;
    let mut parts = Vec::new();

    if let Some(v) = c.min_length {
        parts.push(format!("minLength {v}"));
    }
    if let Some(v) = c.max_length {
        parts.push(format!("maxLength {v}"));
    }
    if let Some(v) = c.min_value {
        parts.push(format!("minimum {v}"));
    }
    if let Some(v) = c.max_value {
        parts.push(format!("maximum {v}"));
    }
    if let Some(v) = &c.pattern {
        parts.push(format!("pattern {v}"));
    }
    if let Some(v) = &c.format {
        parts.push(format!("format {v}"));
    }
    if let Some(v) = c.multiple_of {
        parts.push(format!("multipleOf {v}"));
    }

    if parts.is_empty() {
        None
    } else {
        // not enforced: interfaces validate nothing, so this is documentation
        Some(format!("constraints: {}", parts.join(", ")))
    }
}

/// Render a property name, quoting it when it is not a bare identifier.
fn property_name(name: &str) -> String {
    if is_ts_identifier(name) {
        name.to_string()
    } else {
        format!("\"{}\"", escape(name))
    }
}

/// Whether a string is a valid bare TypeScript property identifier.
fn is_ts_identifier(name: &str) -> bool {
    let mut chars = name.chars();
    match chars.next() {
        Some(c) if c.is_ascii_alphabetic() || c == '_' || c == '$' => {}
        _ => return false,
    }
    chars.all(|c| c.is_ascii_alphanumeric() || c == '_' || c == '$')
}

fn escape(s: &str) -> String {
    s.replace('\\', "\\\\").replace('"', "\\\"")
}

/// Collapse a description to a single line so it cannot break out of a comment.
fn one_line(s: &str) -> String {
    s.replace(['\n', '\r'], " ").trim().to_string()
}

#[cfg(test)]
mod tests {
    use super::*;
    use odk_schema::{
        CompiledField, CompiledModel, CompiledType, CompiledUnion, CompiledUnionVariant,
        FieldConstraints, ScalarType,
    };

    fn scalar(name: ScalarType) -> CompiledType {
        CompiledType::Scalar { name }
    }

    fn schema_with(models: Vec<CompiledModel>) -> CompiledSchema {
        let mut schema = CompiledSchema::new("Test");
        for m in models {
            schema.add_model(m);
        }
        schema
    }

    fn render(schema: &CompiledSchema) -> String {
        generate(schema)
            .get("models.ts")
            .expect("models.ts emitted")
            .clone()
    }

    #[test]
    fn an_empty_schema_emits_nothing() {
        assert!(generate(&CompiledSchema::new("Empty")).is_empty());
    }

    #[test]
    fn a_model_becomes_an_interface() {
        let mut model = CompiledModel::new("Track").with_description("A track");
        model.add_field(CompiledField::new("id", scalar(ScalarType::String)));

        let out = render(&schema_with(vec![model]));

        assert!(out.contains("export interface Track {"));
        assert!(out.contains("// A track"));
        assert!(out.contains("  id: string;\n"));
    }

    #[test]
    fn scalars_map_to_typescript_types() {
        let mut model = CompiledModel::new("M");
        model.add_field(CompiledField::new("s", scalar(ScalarType::String)));
        model.add_field(CompiledField::new("i", scalar(ScalarType::Int64)));
        model.add_field(CompiledField::new("f", scalar(ScalarType::Float64)));
        model.add_field(CompiledField::new("b", scalar(ScalarType::Boolean)));
        model.add_field(CompiledField::new("u", scalar(ScalarType::Unknown)));
        model.add_field(CompiledField::new("t", scalar(ScalarType::UtcDateTime)));

        let out = render(&schema_with(vec![model]));

        assert!(out.contains("s: string;"));
        assert!(out.contains("i: number;"));
        assert!(out.contains("f: number;"));
        assert!(out.contains("b: boolean;"));
        assert!(out.contains("u: unknown;"));
        assert!(out.contains("t: string;"));
    }

    #[test]
    fn optional_fields_use_the_question_mark_marker() {
        let mut model = CompiledModel::new("M");
        model.add_field(CompiledField::new("must", scalar(ScalarType::String)));
        model.add_field(CompiledField::new("maybe", scalar(ScalarType::Int64)).optional());

        let out = render(&schema_with(vec![model]));

        assert!(out.contains("must: string;"));
        assert!(out.contains("maybe?: number;"));
    }

    #[test]
    fn arrays_and_refs_nest() {
        let mut model = CompiledModel::new("M");
        model.add_field(CompiledField::new(
            "tracks",
            CompiledType::Array {
                items: Box::new(CompiledType::Ref {
                    name: "Track".to_string(),
                }),
                length: None,
            },
        ));

        assert!(render(&schema_with(vec![model])).contains("tracks: Track[];"));
    }

    #[test]
    fn an_array_of_a_union_is_parenthesized() {
        let mut model = CompiledModel::new("M");
        model.add_field(CompiledField::new(
            "xs",
            CompiledType::Array {
                items: Box::new(CompiledType::Union {
                    variants: vec![scalar(ScalarType::String), scalar(ScalarType::Int64)],
                }),
                length: None,
            },
        ));

        assert!(render(&schema_with(vec![model])).contains("xs: (string | number)[];"));
    }

    #[test]
    fn a_union_becomes_a_string_literal_alias() {
        let mut schema = CompiledSchema::new("Test");
        schema.add_union(CompiledUnion {
            name: "TrackType".to_string(),
            variants: ["audio", "midi"]
                .iter()
                .map(|v| CompiledUnionVariant {
                    name: (*v).to_string(),
                    variant_type: None,
                })
                .collect(),
            tag: None,
            rename_all: None,
            description: None,
            extensions: odk_schema::Extensions::default(),
            source: None,
        });
        schema.add_model(CompiledModel::new("M"));

        assert!(render(&schema).contains("export type TrackType = \"audio\" | \"midi\";"));
    }

    #[test]
    fn a_data_carrying_union_becomes_a_discriminated_union() {
        fn obj(fields: Vec<CompiledField>) -> CompiledType {
            CompiledType::Object { fields }
        }
        let vec3 = || CompiledType::fixed_array(scalar(ScalarType::Float64), 3);

        let mut schema = CompiledSchema::new("Geo");
        schema.add_union(CompiledUnion {
            name: "OpNode".to_string(),
            tag: Some("op".to_string()),
            rename_all: Some("lowercase".to_string()),
            variants: vec![
                CompiledUnionVariant {
                    name: "cube".to_string(),
                    variant_type: Some(obj(vec![
                        CompiledField::new("size", vec3()),
                        CompiledField::new("center", scalar(ScalarType::Boolean)),
                    ])),
                },
                CompiledUnionVariant {
                    name: "translate".to_string(),
                    variant_type: Some(obj(vec![
                        CompiledField::new("v", vec3()),
                        CompiledField::new("child", CompiledType::reference("OpNode")),
                    ])),
                },
                CompiledUnionVariant {
                    name: "union".to_string(),
                    variant_type: Some(obj(vec![CompiledField::new(
                        "children",
                        CompiledType::array(CompiledType::reference("OpNode")),
                    )])),
                },
            ],
            description: None,
            extensions: odk_schema::Extensions::default(),
            source: None,
        });

        let out = render(&schema);

        assert!(
            out.contains("export type OpNode ="),
            "not a type alias:\n{out}"
        );
        assert!(
            out.contains("{ op: \"cube\"; size: [number, number, number]; center: boolean }"),
            "cube variant / tuple wrong:\n{out}"
        );
        assert!(
            out.contains("{ op: \"translate\"; v: [number, number, number]; child: OpNode }"),
            "translate / recursion wrong:\n{out}"
        );
        assert!(
            out.contains("{ op: \"union\"; children: OpNode[] }"),
            "union / list recursion wrong:\n{out}"
        );
    }

    #[test]
    fn property_names_that_are_not_identifiers_are_quoted() {
        let mut model = CompiledModel::new("M");
        model.add_field(CompiledField::new("kebab-case", scalar(ScalarType::String)));

        let out = render(&schema_with(vec![model]));

        assert!(out.contains("\"kebab-case\": string;"));
    }

    #[test]
    fn constraints_are_emitted_as_comments_not_validation() {
        let mut model = CompiledModel::new("M");
        let mut f = CompiledField::new("tempo", scalar(ScalarType::Float64));
        f.constraints = Some(FieldConstraints {
            min_length: None,
            max_length: None,
            min_value: Some(20.0),
            max_value: Some(300.0),
            pattern: None,
            format: None,
            multiple_of: None,
        });
        model.add_field(f);

        let out = render(&schema_with(vec![model]));
        assert!(out.contains("// constraints: minimum 20, maximum 300"));
    }

    #[test]
    fn descriptions_are_collapsed_so_they_cannot_break_the_comment() {
        let mut model = CompiledModel::new("M");
        let mut f = CompiledField::new("a", scalar(ScalarType::String));
        f.description = Some("line one\nline two".to_string());
        model.add_field(f);

        let out = render(&schema_with(vec![model]));
        assert!(out.contains("// line one line two"));
    }

    #[test]
    fn an_empty_model_is_still_valid_typescript() {
        let out = render(&schema_with(vec![CompiledModel::new("Empty")]));
        assert!(out.contains("export interface Empty {}"));
    }

    #[test]
    fn a_literal_scalar_renders_as_a_literal_type() {
        let mut model = CompiledModel::new("M");
        model.add_field(CompiledField::new(
            "kind",
            CompiledType::Literal {
                value: odk_schema::LiteralValue::String("audio".to_string()),
            },
        ));

        assert!(render(&schema_with(vec![model])).contains("kind: \"audio\";"));
    }
}
